"""Draw a fixed tool-observation sample and, once labeled, score markers.

The sample is deterministic given the pinned first shard of each split.
Labels are stored separately and are not generated by this script.
"""

from __future__ import annotations

import argparse
import json
import random
from datetime import datetime, timezone
from pathlib import Path

import pyarrow.parquet as pq
from huggingface_hub import HfFileSystem

from p8audit.schema import DATASET_ID, PINNED_REVISION
from p8audit.trajectory_parser import parse_trajectory

ROOT = Path(__file__).resolve().parents[1]
SAMPLE_SEED = 20261024
SAMPLE_SIZE = 100

FIRST_SHARDS = {
    ("openhands", "minimax_m25"): "data/minimax_m25_openhands_trajectories/train-00000-of-00020.parquet",
    ("openhands", "qwen35_122b"): "data/qwen35_openhands_trajectories/train-00000-of-00023.parquet",
    ("sweagent", "minimax_m25"): "data/minimax_m25_sweagent_trajectories/train-00000-of-00023.parquet",
    ("sweagent", "qwen35_122b"): "data/qwen35_sweagent_trajectories/train-00000-of-00018.parquet",
}


def _review_view(text: str) -> dict:
    """Keep a short, reviewable view of a tool observation.

    The full observation can be a source listing. The review record stores
    the opening lines, the closing lines, and any lines that match the
    explicit marker vocabulary. Manual labels are made from this view.
    """
    lines = (text or "").splitlines()
    interesting = []
    needles = (
        "Traceback",
        "Error:",
        "Exception:",
        "Panic:",
        "exit code",
        "Exit code",
        "returncode",
        "FAILED",
        "FAILURES",
        "--- FAIL:",
        "test result:",
        "FAIL ",
    )
    for line in lines:
        if any(needle in line for needle in needles):
            interesting.append(line[:240])
        if len(interesting) >= 8:
            break
    return {
        "n_lines": len(lines),
        "head": "\n".join(lines[:8])[:1200],
        "tail": "\n".join(lines[-6:])[:800],
        "signal_lines": interesting,
    }


def draw_sample() -> list[dict]:
    fs = HfFileSystem()
    rng = random.Random(SAMPLE_SEED)
    per_group = SAMPLE_SIZE // len(FIRST_SHARDS)
    chosen: list[dict] = []
    for (config, split), path in FIRST_SHARDS.items():
        remote = f"datasets/{DATASET_ID}@{PINNED_REVISION}/{path}"
        print(f"SAMPLE {config}/{split}", flush=True)
        with fs.open(remote, "rb") as handle:
            table = pq.ParquetFile(handle).read(
                columns=["instance_id", "repo", "resolved", "language", "trajectory"]
            )
        candidates = []
        trajectories = table.column("trajectory")
        instances = table.column("instance_id").to_pylist()
        repos = table.column("repo").to_pylist()
        resolved = table.column("resolved").to_pylist()
        languages = table.column("language").to_pylist()
        # Fixed row subsample before walking tool messages, so the draw does
        # not depend on scanning every observation in the shard.
        row_indexes = list(range(table.num_rows))
        rng.shuffle(row_indexes)
        for row_index in row_indexes[:80]:
            parsed = parse_trajectory(trajectories[row_index].as_py())
            for cycle in parsed.cycles:
                for obs_index, markers in zip(cycle.observation_indexes, cycle.markers, strict=True):
                    message = parsed.messages[obs_index]
                    candidates.append(
                        {
                            "config": config,
                            "split": split,
                            "shard": path,
                            "row_index": row_index,
                            "instance_id": instances[row_index],
                            "repo": repos[row_index],
                            "language": languages[row_index],
                            "resolved": resolved[row_index],
                            "message_index": message.index,
                            "tool_names": list(cycle.tool_names),
                            "cycle_status": cycle.status,
                            "review": _review_view(message.content),
                            "content_sha1_16": _digest(message.content),
                            "n_chars": len(message.content or ""),
                            "predicted_explicit_error": markers.explicit_error,
                            "predicted_test_failure": markers.explicit_test_failure,
                            "predicted_test_pass": markers.explicit_test_pass,
                            "error_reasons": list(markers.error_reasons),
                            "test_failure_reasons": list(markers.test_failure_reasons),
                            "test_pass_reasons": list(markers.test_pass_reasons),
                        }
                    )
        rng.shuffle(candidates)
        chosen.extend(candidates[:per_group])
    for index, row in enumerate(chosen):
        row["sample_id"] = f"s{index:03d}"
    return chosen


def _digest(text: str) -> str:
    import hashlib

    return hashlib.sha1((text or "").encode("utf-8")).hexdigest()[:16]


def score(sample: list[dict], labels: dict[str, dict]) -> dict:
    fields = (
        ("explicit_error", "predicted_explicit_error", "label_explicit_error"),
        ("explicit_test_failure", "predicted_test_failure", "label_test_failure"),
        ("explicit_test_pass", "predicted_test_pass", "label_test_pass"),
    )
    report = {"n": 0, "missing_labels": [], "metrics": {}}
    matched = []
    for row in sample:
        label = labels.get(row["sample_id"])
        if label is None:
            report["missing_labels"].append(row["sample_id"])
            continue
        matched.append((row, label))
    report["n"] = len(matched)
    for name, pred_key, label_key in fields:
        tp = fp = fn = tn = 0
        disagreements = []
        for row, label in matched:
            pred = bool(row[pred_key])
            truth = bool(label[label_key])
            if pred and truth:
                tp += 1
            elif pred and not truth:
                fp += 1
                disagreements.append({"sample_id": row["sample_id"], "kind": "false_positive", "field": name})
            elif not pred and truth:
                fn += 1
                disagreements.append({"sample_id": row["sample_id"], "kind": "false_negative", "field": name})
            else:
                tn += 1
        precision = tp / (tp + fp) if (tp + fp) else None
        recall = tp / (tp + fn) if (tp + fn) else None
        report["metrics"][name] = {
            "tp": tp,
            "fp": fp,
            "fn": fn,
            "tn": tn,
            "precision": precision,
            "recall": recall,
            "disagreements": disagreements,
        }
    return report


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=("draw", "score"), default="draw")
    args = parser.parse_args()
    review_dir = ROOT / "artifacts" / "reviews"
    review_dir.mkdir(parents=True, exist_ok=True)
    sample_path = review_dir / "tool_observation_sample.jsonl"
    if args.mode == "draw":
        rows = draw_sample()
        with sample_path.open("w", encoding="utf-8") as handle:
            for row in rows:
                handle.write(json.dumps(row, ensure_ascii=False) + "\n")
        print("WROTE", sample_path, "n", len(rows))
        return
    rows = [json.loads(line) for line in sample_path.read_text(encoding="utf-8").splitlines() if line]
    label_path = review_dir / "tool_observation_labels.json"
    labels = {row["sample_id"]: row for row in json.loads(label_path.read_text(encoding="utf-8"))}
    report = score(rows, labels)
    report["generated_at_utc"] = datetime.now(timezone.utc).isoformat()
    report["seed"] = SAMPLE_SEED
    report["revision"] = PINNED_REVISION
    out = ROOT / "artifacts" / "manifests" / "parser_validation.json"
    out.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report["metrics"], indent=2))


if __name__ == "__main__":
    main()
